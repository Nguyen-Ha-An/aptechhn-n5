import { describe, it, expect } from 'vitest';
import { extractOtpCode } from '../../e2e/helpers/mail';

describe('extractOtpCode', () => {
  it('extracts code from strong HTML tags as generated by magic_link.html', () => {
    const html = `
      <p style="margin-bottom: 16px;">Or enter this code: <strong>654321</strong></p>
    `;
    expect(extractOtpCode(html)).toBe('654321');
  });

  it('extracts code prefixed with code:', () => {
    const text = 'Your verification code: 123456. Valid for 1 hour.';
    expect(extractOtpCode(text)).toBe('123456');
  });

  it('extracts code prefixed with token:', () => {
    const text = 'token: 987654';
    expect(extractOtpCode(text)).toBe('987654');
  });

  it('extracts any standalone 6-digit sequence', () => {
    const text = 'Your temporary login passcode is 812390';
    expect(extractOtpCode(text)).toBe('812390');
  });

  it('returns null when no 6-digit code is found', () => {
    expect(extractOtpCode('Hello world without any code')).toBeNull();
    expect(extractOtpCode('12345')).toBeNull();
    expect(extractOtpCode('1234567')).toBeNull();
  });
});
